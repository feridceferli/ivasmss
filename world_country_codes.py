def region_flag(iso):
    if len(iso) != 2 or not iso.isalpha():
        return "🌍"
    return "".join(chr(ord(ch) - ord("A") + 0x1F1E6) for ch in iso.upper())


def build_all_country_rows(services):
    """Return every listed country, with only upstream-announced ranges.

    Use longest matching calling code so +1246 is not mistaken for +1.
    Shared calling codes (+1, +7, etc.) remain separate country rows,
    but do not imply a provider range belongs uniquely to either region.
    """
    countries = [{
        "iso": iso, "name": name, "flag": region_flag(iso), "prefix": code,
        "ranges": [], "is_shared": False,
    } for iso, name, code in WORLD_COUNTRIES]
    by_code = {}
    for c in countries:
        by_code.setdefault(c["prefix"], []).append(c)
    for group in by_code.values():
        if len(group) > 1:
            for c in group:
                c["is_shared"] = True
    known_codes = sorted(by_code, key=len, reverse=True)
    seen = {}
    for service, ranges in sorted((services or {}).items()):
        if not isinstance(ranges, (list, tuple)):
            continue
        for raw in ranges:
            rid = re.sub(r"\D", "", str(raw))
            if not rid or len(rid) > 10:
                continue
            match = next((cc for cc in known_codes if rid.startswith(cc)), None)
            if not match:
                continue
            seen.setdefault(match, {})[rid] = {
                "rid": rid, "display": str(raw), "service": str(service),
            }
    for code, group in by_code.items():
        matches = sorted(seen.get(code, {}).values(), key=lambda row: row["rid"])
        for country in group:
            country["ranges"] = matches
    return sorted(countries, key=lambda c: (c["name"].casefold(), c["iso"]))
